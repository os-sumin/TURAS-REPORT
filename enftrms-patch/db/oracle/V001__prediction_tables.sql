-- 1) 정답값 (엑셀 양식 적재용) ----------------------------------------
CREATE TABLE TFEE_PRED_ANSWER (
    SBJT_ID              VARCHAR2(50)  NOT NULL,
    FRUT_OWN_ORGN_ID     VARCHAR2(50)  NOT NULL,
    TECH_IPMT_ORGN_ID    VARCHAR2(50),
    BASE_YEAR            NUMBER(4),
    TTL_PAY_GVSTM_AM     NUMBER(18)    DEFAULT 0,
    TTL_USE_GVSTM_AM     NUMBER(18)    DEFAULT 0,
    SALES_OCCUR_YN       CHAR(1)       DEFAULT 'N',
    RND_INCOME_AM        NUMBER(18)    DEFAULT 0,
    TECH_CTRB_PT         NUMBER(7,4)   DEFAULT 0,
    TFEE_AM              NUMBER(18)    DEFAULT 0,
    ANSWER_Y             NUMBER(1),
    EXCEL_BATCH_ID       VARCHAR2(50),
    FRST_REG_MBR_ID      VARCHAR2(50),
    FRST_REG_DT          TIMESTAMP     DEFAULT SYSTIMESTAMP,
    LAST_MODF_MBR_ID     VARCHAR2(50),
    LAST_MODF_DT         TIMESTAMP     DEFAULT SYSTIMESTAMP,
    CONSTRAINT PK_TFEE_PRED_ANSWER PRIMARY KEY (SBJT_ID, FRUT_OWN_ORGN_ID, BASE_YEAR)
);
CREATE INDEX IX_TFEE_PRED_ANSWER_01 ON TFEE_PRED_ANSWER(FRUT_OWN_ORGN_ID, ANSWER_Y);

-- 2) 예측 결과 헤더 ---------------------------------------------------
CREATE TABLE TFEE_PRED_RESULT (
    PRED_ID              NUMBER(18)    NOT NULL,
    SBJT_ID              VARCHAR2(50)  NOT NULL,
    ORGN_ID              VARCHAR2(50)  NOT NULL,
    PRED_AT              TIMESTAMP     DEFAULT SYSTIMESTAMP,
    TOTAL_SCORE          NUMBER(5,2)   DEFAULT 0,
    GRADE_CD             VARCHAR2(20),
    PROBABILITY_PT       NUMBER(5,4),
    RULE_VERSION         VARCHAR2(20),
    RECOMM_ACTION        VARCHAR2(200),
    FRST_REG_MBR_ID      VARCHAR2(50),
    FRST_REG_DT          TIMESTAMP     DEFAULT SYSTIMESTAMP,
    CONSTRAINT PK_TFEE_PRED_RESULT PRIMARY KEY (PRED_ID)
);
CREATE INDEX IX_TFEE_PRED_RESULT_01 ON TFEE_PRED_RESULT(SBJT_ID, ORGN_ID, PRED_AT DESC);
CREATE INDEX IX_TFEE_PRED_RESULT_02 ON TFEE_PRED_RESULT(GRADE_CD, TOTAL_SCORE DESC);

CREATE SEQUENCE SEQ_TFEE_PRED_ID START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

-- 3) 차원별 점수 (5행/예측) -------------------------------------------
CREATE TABLE TFEE_PRED_DIM_SCORE (
    PRED_ID              NUMBER(18)    NOT NULL,
    DIM_CD               VARCHAR2(10)  NOT NULL,
    DIM_SCORE            NUMBER(5,2)   DEFAULT 0,
    MAX_SCORE            NUMBER(5,2)   DEFAULT 20,
    RULE_DETAIL          CLOB,
    CONSTRAINT PK_TFEE_PRED_DIM_SCORE PRIMARY KEY (PRED_ID, DIM_CD),
    CONSTRAINT FK_TFEE_PRED_DIM_SCORE FOREIGN KEY (PRED_ID) REFERENCES TFEE_PRED_RESULT(PRED_ID) ON DELETE CASCADE
);

-- 4) 요인 (긍정/부정/확인필요) ---------------------------------------
CREATE TABLE TFEE_PRED_FACTOR (
    PRED_ID              NUMBER(18)    NOT NULL,
    FACTOR_SEQ           NUMBER(4)     NOT NULL,
    FACTOR_TP            VARCHAR2(10)  NOT NULL,
    FACTOR_TEXT          VARCHAR2(500),
    SOURCE_CD            VARCHAR2(50),
    CONSTRAINT PK_TFEE_PRED_FACTOR PRIMARY KEY (PRED_ID, FACTOR_SEQ),
    CONSTRAINT FK_TFEE_PRED_FACTOR FOREIGN KEY (PRED_ID) REFERENCES TFEE_PRED_RESULT(PRED_ID) ON DELETE CASCADE
);

-- 5) 외부 신호 정규화 적재 -------------------------------------------
CREATE TABLE TFEE_PRED_EXT_SIGNAL (
    SIGNAL_ID            NUMBER(18)    NOT NULL,
    ORGN_ID              VARCHAR2(50)  NOT NULL,
    SBJT_ID              VARCHAR2(50),
    SOURCE_CD            VARCHAR2(20)  NOT NULL,
    SIGNAL_TP            VARCHAR2(30)  NOT NULL,
    SIGNAL_DT            DATE,
    AMOUNT               NUMBER(18),
    RAW_JSON             CLOB,
    COLLECTED_AT         TIMESTAMP     DEFAULT SYSTIMESTAMP,
    CONSTRAINT PK_TFEE_PRED_EXT_SIGNAL PRIMARY KEY (SIGNAL_ID)
);
CREATE INDEX IX_TFEE_PRED_EXT_01 ON TFEE_PRED_EXT_SIGNAL(ORGN_ID, SIGNAL_DT DESC);
CREATE INDEX IX_TFEE_PRED_EXT_02 ON TFEE_PRED_EXT_SIGNAL(SOURCE_CD, SIGNAL_TP);
CREATE SEQUENCE SEQ_TFEE_PRED_EXT START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

-- 6) 룰셋 버전 스냅샷 ------------------------------------------------
CREATE TABLE TFEE_PRED_RULE_VER (
    RULE_VERSION         VARCHAR2(20)  NOT NULL,
    RULE_YAML            CLOB,
    EFFECTIVE_FROM       DATE          DEFAULT TRUNC(SYSDATE),
    FRST_REG_MBR_ID      VARCHAR2(50),
    FRST_REG_DT          TIMESTAMP     DEFAULT SYSTIMESTAMP,
    CONSTRAINT PK_TFEE_PRED_RULE_VER PRIMARY KEY (RULE_VERSION)
);
